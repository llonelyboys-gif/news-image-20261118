/** Width of one character cell (glyph plus its gap column) at a size. */
export function cellW(size: number): number {
  return 4 * size;
}

/** Height of one text line at a size. */
export function cellH(size: number): number {
  return 5 * size;
}

/** Pixel width of a string at a size (no trailing gap). */
export function measure(text: string, size: number): number {
  return text.length * cellW(size) - size;
}

export function print(sheet: Sheet, text: string, x: number, y: number, size: number, c: Colour): void {
  const upper = text.toUpperCase();
  for (let i = 0; i < upper.length; i++) {
    const glyph = GLYPHS[upper[i]] ?? [0, 0, 0, 0, 0];
    const ox = x + i * cellW(size);
    for (let row = 0; row < 5; row++) {
      const bits = glyph[row];
      for (let col = 0; col < 3; col++) {
        if (bits & (1 << (2 - col))) sheet.box(ox + col * size, y + row * size, size, size, c);
      }
    }
  }
}

/** Break text into lines that fit maxWidth, breaking only between words. */
export function wrap(text: string, maxWidth: number, size: number): string[] {
  const words = text.split(' ');
  const out: string[] = [];
  let line = '';
  for (const w of words) {
    const next = line ? line + ' ' + w : w;
    if (measure(next, size) <= maxWidth) {
      line = next;
    } else {
      if (line) out.push(line);
      line = w;
    }
  }
  if (line) out.push(line);
  return out;
}

/** Draw wrapped text; returns the y just below the last line drawn. */
export function flow(
  sheet: Sheet,
  text: string,
  x: number,
  y: number,
  maxWidth: number,
  size: number,
  c: Colour,
): number {
  const lines = wrap(text, maxWidth, size);
  const step = cellH(size) + 7;
  for (let i = 0; i < lines.length; i++) print(sheet, lines[i], x, y + i * step, size, c);
  return y + lines.length * step;
}
